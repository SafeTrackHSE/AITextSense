/**
 * Export the cleaned/edited text (Markdown source) to common document formats:
 * Markdown, plain text, HTML, PDF, and Word (.docx).
 */
import { marked, type Tokens } from 'marked';
import { saveAs } from 'file-saver';
import { sanitizeHtmlFragment } from '../../lib/sanitizeHtml';
import type { AnalysisReport } from '../report/schema';
import { exportReportDOCX } from '../report/export';

marked.setOptions({ breaks: true });

function htmlDoc(bodyHtml: string): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="generator" content="AI TextSense — © 2026 Wilson Volpe">
<title>AI TextSense — Cleaned Text</title>
<style>
  body { font-family: -apple-system, Segoe UI, Roboto, sans-serif; line-height: 1.6; max-width: 720px; margin: 40px auto; padding: 0 20px; color: #1a1a1a; }
  h1,h2,h3 { line-height: 1.25; }
  code { background: #f0f0f0; padding: 0.1em 0.3em; border-radius: 3px; }
  blockquote { border-left: 3px solid #ccc; margin: 0; padding-left: 1em; color: #555; }
</style>
</head>
<body>
${bodyHtml}
</body>
</html>`;
}

/** Strip Markdown to readable plain text (headings, emphasis, list markers removed). */
export function toPlainText(md: string): string {
  return md
    .replace(/^#{1,6}\s+/gm, '')
    .replace(/^\s*[-*+]\s+/gm, '• ')
    .replace(/^\s*\d+\.\s+/gm, (m) => m)
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(.+?)\*/g, '$1')
    .replace(/`(.+?)`/g, '$1')
    .replace(/^>\s?/gm, '')
    .trim();
}

export function exportMarkdown(md: string, filename = 'cleaned.md'): void {
  saveAs(new Blob([md], { type: 'text/markdown;charset=utf-8' }), filename);
}

export function exportPlainText(md: string, filename = 'cleaned.txt'): void {
  saveAs(new Blob([toPlainText(md)], { type: 'text/plain;charset=utf-8' }), filename);
}

export function exportHtml(md: string, filename = 'cleaned.html'): void {
  // Sanitize before writing to disk — the exported file may be opened in a
  // browser elsewhere, so it must not carry an XSS/beacon payload from the input.
  const body = sanitizeHtmlFragment(marked.parse(md) as string);
  saveAs(new Blob([htmlDoc(body)], { type: 'text/html;charset=utf-8' }), filename);
}

export async function exportPdf(md: string, filename = 'cleaned.pdf'): Promise<void> {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const margin = 48;
  const width = doc.internal.pageSize.getWidth() - margin * 2;
  const pageH = doc.internal.pageSize.getHeight();
  let y = margin;

  const line = (text: string, size: number, bold: boolean, indent = 0) => {
    doc.setFont('helvetica', bold ? 'bold' : 'normal');
    doc.setFontSize(size);
    const wrapped = doc.splitTextToSize(text, width - indent);
    for (const w of wrapped) {
      if (y > pageH - margin) { doc.addPage(); y = margin; }
      doc.text(w, margin + indent, y);
      y += size * 1.35;
    }
  };

  for (const raw of md.split('\n')) {
    const l = raw.trimEnd();
    if (!l.trim()) { y += 8; continue; }
    const h = l.match(/^(#{1,3})\s+(.*)$/);
    if (h) { y += 6; line(h[2], h[1].length === 1 ? 18 : h[1].length === 2 ? 15 : 13, true); y += 2; continue; }
    const bullet = l.match(/^\s*[-*+]\s+(.*)$/);
    if (bullet) { line('•  ' + stripInline(bullet[1]), 11, false, 14); continue; }
    const num = l.match(/^\s*(\d+)\.\s+(.*)$/);
    if (num) { line(`${num[1]}.  ` + stripInline(num[2]), 11, false, 14); continue; }
    line(stripInline(l), 11, false);
  }

  // Footer
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(140);
  doc.text('Generated by AI TextSense · © 2026 Wilson Volpe', margin, pageH - 20);

  doc.save(filename);
}

function stripInline(s: string): string {
  return s.replace(/\*\*(.+?)\*\*/g, '$1').replace(/\*(.+?)\*/g, '$1').replace(/`(.+?)`/g, '$1');
}

export async function exportDocx(md: string, filename = 'cleaned.docx'): Promise<void> {
  const { Document, Packer, Paragraph, TextRun, HeadingLevel } = await import('docx');
  const tokens = marked.lexer(md);
  const paras: InstanceType<typeof Paragraph>[] = [];

  const inlineRuns = (text: string): InstanceType<typeof TextRun>[] => {
    // Minimal inline parse for **bold** and *italic*.
    const runs: InstanceType<typeof TextRun>[] = [];
    const re = /(\*\*(.+?)\*\*|\*(.+?)\*)/g;
    let last = 0; let m: RegExpExecArray | null;
    while ((m = re.exec(text)) !== null) {
      if (m.index > last) runs.push(new TextRun(text.slice(last, m.index)));
      if (m[2] != null) runs.push(new TextRun({ text: m[2], bold: true }));
      else if (m[3] != null) runs.push(new TextRun({ text: m[3], italics: true }));
      last = m.index + m[0].length;
    }
    if (last < text.length) runs.push(new TextRun(text.slice(last)));
    return runs.length ? runs : [new TextRun(text)];
  };

  for (const t of tokens as Tokens.Generic[]) {
    if (t.type === 'heading') {
      const level = (t as Tokens.Heading).depth;
      paras.push(new Paragraph({
        heading: level === 1 ? HeadingLevel.HEADING_1 : level === 2 ? HeadingLevel.HEADING_2 : HeadingLevel.HEADING_3,
        children: inlineRuns((t as Tokens.Heading).text),
      }));
    } else if (t.type === 'list') {
      const list = t as Tokens.List;
      list.items.forEach((it, i) => {
        paras.push(list.ordered
          ? new Paragraph({ children: inlineRuns(`${(list.start || 1) + i}.  ${it.text}`) })
          : new Paragraph({ children: inlineRuns(it.text), bullet: { level: 0 } }));
      });
    } else if (t.type === 'paragraph') {
      paras.push(new Paragraph({ children: inlineRuns((t as Tokens.Paragraph).text) }));
    } else if (t.type === 'space') {
      // skip
    } else if ('text' in t && typeof (t as unknown as { text?: string }).text === 'string') {
      paras.push(new Paragraph({ children: inlineRuns((t as unknown as { text: string }).text) }));
    }
  }

  if (paras.length === 0) paras.push(new Paragraph({ children: [new TextRun(toPlainText(md))] }));

  const docxDoc = new Document({ sections: [{ children: paras }] });
  const blob = await Packer.toBlob(docxDoc);
  saveAs(blob, filename);
}

export type ExportFormat = 'markdown' | 'text' | 'html' | 'pdf' | 'docx';

export async function exportAs(format: ExportFormat, md: string): Promise<void> {
  switch (format) {
    case 'markdown': return exportMarkdown(md);
    case 'text': return exportPlainText(md);
    case 'html': return exportHtml(md);
    case 'pdf': return exportPdf(md);
    case 'docx': return exportDocx(md);
  }
}

/**
 * Export full executive forensic report as a Word (.docx) document
 */
export async function exportReportAsDocx(
  report: AnalysisReport,
  filename = 'forensic-report.docx'
): Promise<Blob> {
  const blob = await exportReportDOCX(report);
  if (typeof window !== 'undefined' && typeof document !== 'undefined') {
    saveAs(blob, filename);
  }
  return blob;
}

export { exportReportDOCX };

